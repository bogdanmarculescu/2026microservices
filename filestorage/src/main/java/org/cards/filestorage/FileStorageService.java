package org.cards.filestorage;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.Resource;
import org.springframework.core.io.UrlResource;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.UUID;

@Service
@Slf4j
public class FileStorageService {
    private final Path root;

    public FileStorageService(
            @Value("${file.storage.path:/data/files}")
            String path) throws IOException {
        root = Path.of(path).toAbsolutePath().normalize();
        Files.createDirectories(root);
    }

    public String storeById(MultipartFile file) throws IOException {
        if (file.isEmpty()) {
            throw new IllegalArgumentException("File is empty");
        }

        String id = UUID.randomUUID().toString();
        Path destination = root.resolve(id).normalize();

        if (!destination.startsWith(root)) {
            throw new IllegalArgumentException("Invalid path");
        }

        try (InputStream input = file.getInputStream()) {
            Files.copy(
                    input,
                    destination,
                    StandardCopyOption.REPLACE_EXISTING
            );
        }

        return id;
    }

    public String store(MultipartFile file) throws IOException {
        if (file.isEmpty()) {
            throw new IllegalArgumentException("File is empty");
        }

        String filename = file.getOriginalFilename();
        validateFilename(filename);

        Path destination = root.resolve(filename).normalize();

        // Do not silently overwrite an existing file.
        if (Files.exists(destination)) {
            throw new IllegalArgumentException("File already exists: " + filename);
        }

        try (InputStream input = file.getInputStream()) {
            Files.copy(input, destination);
        }

        return filename;
    }

    public Resource loadById(String id) throws IOException {
        // Only accept identifiers generated by this service.
        UUID.fromString(id);

        Path file = root.resolve(id).normalize();

        if (!file.startsWith(root) || !Files.isRegularFile(file)) {
            throw new java.nio.file.NoSuchFileException(id);
        }

        return new UrlResource(file.toUri());
    }

    public Resource load(String filename) throws IOException {
        validateFilename(filename);

        Path file = root.resolve(filename).normalize();

        if (!file.startsWith(root) || !Files.isRegularFile(file)) {
            throw new java.nio.file.NoSuchFileException(filename);
        }

        return new UrlResource(file.toUri());
    }

    public void deleteById(String id) throws IOException {
        UUID.fromString(id);
        Path file = root.resolve(id).normalize();

        if (!file.startsWith(root)) {
            throw new IllegalArgumentException("Invalid path");
        }

        Files.deleteIfExists(file);
    }

    public void delete(String filename) throws IOException {
        validateFilename(filename);
        Path file = root.resolve(filename).normalize();

        if (!file.startsWith(root)) {
            throw new IllegalArgumentException("Invalid path");
        }

        Files.delete(file);
    }

    private void validateFilename(String filename){
        if(filename == null || filename.isBlank()
        || filename.equals(".")
        || filename.equals("..")
        || filename.contains("/")
        || filename.contains("\\")
        || filename.contains(":")){
            throw new IllegalArgumentException("Invalid Filename");
        }

    }
}
